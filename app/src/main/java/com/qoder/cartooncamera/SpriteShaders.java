package com.qoder.cartooncamera;

/** 小精灵与粒子（爱心/星星/涟漪）的着色器：全程序化 SDF 绘制，不依赖贴图。 */
final class SpriteShaders {

    private SpriteShaders() {
    }

    private static String glsl(String... lines) {
        return String.join("\n", lines);
    }

    /** 精灵四边形：局部坐标 -1..1，按屏幕像素比例保持圆形，支持旋转与镜像。 */
    static final String VS_SPRITE = glsl(
            "attribute vec2 aPos;",
            "uniform vec2 uCenter;",
            "uniform vec2 uHalf;",
            "uniform float uRot;",
            "uniform float uMirror;",
            "varying vec2 vP;",
            "void main() {",
            "  vec2 local = aPos * 2.0 - 1.0;",
            "  vP = local;",
            // uHalf 已按像素比例修正，直接在局部空间旋转即为屏幕上的刚体旋转
            "  float c = cos(uRot);",
            "  float s = sin(uRot);",
            "  vec2 r = vec2(local.x * c - local.y * s, local.x * s + local.y * c);",
            "  vec2 off = r * uHalf;",
            "  if (uMirror > 0.5) { off.x = -off.x; }",
            "  gl_Position = vec4(uCenter + off, 0.0, 1.0);",
            "}"
    );

    static final String FS_SPRITE = glsl(
            "precision mediump float;",
            "varying vec2 vP;",
            "uniform float uShape;",    // 0 精灵 1 爱心 2 星星 3 涟漪环 4 烟雾
            "uniform vec3 uTint;",
            "uniform float uMood;",     // 0 平常 1 惊吓 2 开心 3 挤压 4 好奇 5 生气 6 困倦
            "uniform float uBlink;",
            "uniform float uTime;",
            "uniform float uSeed;",
            "uniform vec2 uSquash;",
            "uniform vec2 uLook;",
            "uniform float uAA;",
            "uniform float uAlpha;",
            "uniform float uSpecies;",  // 0 圆团 1 胖梨 2 猫耳 3 水母 4 石头 5 萝卜苗 6 星星仔 7 刺球
            "uniform float uTemper;",   // 0 好脾气 .. 1 坏脾气
            "uniform float uBounce;",   // 弹跳幅度（活泼的蹦得高）
            "float sdSeg(vec2 p, vec2 a, vec2 b, float r) {",
            "  vec2 pa = p - a;",
            "  vec2 ba = b - a;",
            "  float h = clamp(dot(pa, ba) / max(dot(ba, ba), 0.0001), 0.0, 1.0);",
            "  return length(pa - ba * h) - r;",
            "}",
            "float sdBox(vec2 p, vec2 b, float r) {",
            "  vec2 d = abs(p) - b + r;",
            "  return length(max(d, 0.0)) + min(max(d.x, d.y), 0.0) - r;",
            "}",
            "vec2 rot2(vec2 p, float a) {",
            "  float c = cos(a), s = sin(a);",
            "  return vec2(p.x * c - p.y * s, p.x * s + p.y * c);",
            "}",
            // 等腰三角（耳朵）：底在 q.y=0，尖在 q.y=h
            "float sdTri(vec2 q, float w, float h) {",
            "  return max(max(abs(q.x) - w * (1.0 - clamp(q.y / h, 0.0, 1.0)), q.y - h), -q.y);",
            "}",
            "float feet(vec2 p, float dx, float y, float r) {",
            "  return min(length((p - vec2(-dx, y)) * vec2(1.0, 0.85)) - r,",
            "             length((p - vec2( dx, y)) * vec2(1.0, 0.85)) - r);",
            "}",
            "float arms(vec2 p, float dx, float y, float r) {",
            "  return min(length((p - vec2(-dx, y)) * vec2(1.3, 1.0)) - r,",
            "             length((p - vec2( dx, y)) * vec2(1.3, 1.0)) - r);",
            "}",
            "float m(float d) { return 1.0 - smoothstep(-uAA, uAA, d); }",
            "void creature() {",
            "  vec2 p = vP;",
            "  p.x /= uSquash.x;",
            "  p.y /= uSquash.y;",
            "  float bob = sin(uTime * (2.1 + uBounce * 1.5) + uSeed * 6.283) * 0.035 * uBounce;",
            "  p.y -= bob;",
            "  float startle = step(0.5, uMood) * step(uMood, 1.5);",
            "  float happy   = step(1.5, uMood) * step(uMood, 2.5);",
            "  float squish  = step(2.5, uMood) * step(uMood, 3.5);",
            "  float curious = step(3.5, uMood) * step(uMood, 4.5);",
            "  float angry   = step(4.5, uMood) * step(uMood, 5.5);",
            "  float sleepy  = step(5.5, uMood);",
            // 坏脾气的会气得发抖
            "  p.x += sin(uTime * 34.0 + uSeed * 10.0) * 0.014 * angry;",
            "  vec2 look = uLook * 0.035;",
            "  float dBody = 1e5;",
            "  float dAcc = 1e5;",
            "  float dTip = 1e5;",
            "  float whisk = 0.0;",
            "  float eY = 0.12;",
            "  float eDX = 0.215;",
            "  float eR = 0.082;",
            "  float mY = -0.10;",
            "  float mW = 0.125;",
            "  float sp = uSpecies;",
            "  if (sp < 0.5) {",                       // 圆团：两只触角
            "    dBody = length(p * vec2(1.0, 0.94)) - 0.60;",
            "    float side = step(0.0, p.x) * 2.0 - 1.0;",
            "    float perk = startle * 0.12 + curious * 0.06 + angry * 0.05;",
            "    vec2 a0 = vec2(side * 0.20, 0.40);",
            "    vec2 a1 = vec2(side * (0.38 + perk), 0.66 + perk);",
            "    dAcc = sdSeg(p, a0, a1, 0.046);",
            "    dTip = length(p - a1) - (0.10 + startle * 0.02);",
            "    dAcc = min(dAcc, arms(p, 0.60, -0.02, 0.125));",
            "    dAcc = min(dAcc, feet(p, 0.22, -0.56, 0.15));",
            "  } else if (sp < 1.5) {",                // 胖梨：上小下大
            "    dBody = min(length(p - vec2(0.0, -0.16)) - 0.50,",
            "                 length(p - vec2(0.0, 0.28)) - 0.33);",
            "    dAcc = arms(p, 0.46, -0.06, 0.10);",
            "    dAcc = min(dAcc, feet(p, 0.20, -0.60, 0.13));",
            "    eY = 0.10; eDX = 0.19; eR = 0.075; mY = -0.12; mW = 0.115;",
            "  } else if (sp < 2.5) {",                // 猫耳：三角耳 + 胡须 + 尾巴
            "    dBody = length(p * vec2(1.04, 0.98)) - 0.56;",
            "    dAcc = min(sdTri(rot2(p - vec2(-0.34, 0.30), 0.28), 0.20, 0.30),",
            "               sdTri(rot2(p - vec2( 0.34, 0.30), -0.28), 0.20, 0.30));",
            "    dAcc = min(dAcc, feet(p, 0.24, -0.54, 0.13));",
            "    dAcc = min(dAcc, sdSeg(p, vec2(0.50, -0.28), vec2(0.72, -0.18), 0.042));",
            "    dAcc = min(dAcc, sdSeg(p, vec2(0.72, -0.18), vec2(0.78, 0.06), 0.040));",
            "    whisk = 1.0;",
            "    eY = 0.08; eDX = 0.20; eR = 0.080; mY = -0.12; mW = 0.105;",
            "  } else if (sp < 3.5) {",                // 水母：圆顶 + 四条飘带
            "    dBody = max(length(p * vec2(1.0, 1.06)) - 0.58, -(p.y + 0.08));",
            "    dAcc = sdBox(p - vec2(0.0, -0.14), vec2(0.50, 0.07), 0.07);",
            "    for (int i = 0; i < 4; i++) {",
            "      float fi = float(i);",
            "      float x0 = -0.36 + 0.24 * fi;",
            "      float sway = sin(uTime * 2.4 + fi * 1.7 + uSeed * 6.0) * 0.06;",
            "      dAcc = min(dAcc, sdSeg(p, vec2(x0, -0.18), vec2(x0 + sway, -0.58), 0.032));",
            "    }",
            "    eY = 0.08; eDX = 0.19; eR = 0.078; mY = -0.12; mW = 0.115;",
            "  } else if (sp < 4.5) {",                // 石头：方头方脑
            "    dBody = sdBox(p - vec2(0.0, -0.02), vec2(0.54, 0.40), 0.20);",
            "    dAcc = feet(p, 0.24, -0.46, 0.11);",
            "    eY = 0.04; eDX = 0.19; eR = 0.068; mY = -0.17; mW = 0.11;",
            "  } else if (sp < 5.5) {",                // 萝卜苗：高个 + 两片叶
            "    dBody = length(p * vec2(1.62, 1.0)) - 0.60;",
            "    dAcc = min(length(rot2(p - vec2(-0.18, 0.56), 0.55) * vec2(1.9, 1.0)) - 0.15,",
            "               length(rot2(p - vec2( 0.18, 0.56), -0.55) * vec2(1.9, 1.0)) - 0.15);",
            "    dAcc = min(dAcc, sdSeg(p, vec2(0.0, 0.36), vec2(0.0, 0.60), 0.026));",
            "    eY = 0.10; eDX = 0.15; eR = 0.062; mY = -0.08; mW = 0.095;",
            "  } else if (sp < 6.5) {",                // 星星仔：五角星身体
            "    float ang0 = atan(p.y, p.x);",
            "    dBody = length(p) - (0.42 + 0.18 * cos(5.0 * ang0 + 1.5708));",
            "    eY = 0.03; eDX = 0.125; eR = 0.056; mY = -0.09; mW = 0.085;",
            "  } else {",                              // 刺球：一圈尖刺
            "    float ang0 = atan(p.y, p.x) + sin(uTime * 1.3 + uSeed * 6.0) * 0.03;",
            "    dBody = length(p) - (0.48 + 0.10 * (0.5 + 0.5 * cos(ang0 * 12.0)));",
            "    dAcc = feet(p, 0.20, -0.52, 0.12);",
            "    eY = 0.06; eDX = 0.19; eR = 0.070; mY = -0.10; mW = 0.105;",
            "  }",
            "  float d = min(dBody, min(dAcc, dTip));",
            "  float fill = m(d);",
            "  float rim = smoothstep(-0.10, -0.03, d) * fill;",
            "  float shadow = smoothstep(0.60, 0.06, length((p + vec2(0.0, 0.62)) * vec2(1.0, 3.2)));",
            "  vec3 col = uTint * (0.78 + 0.5 * clamp(0.58 - p.y * 0.55, 0.0, 1.0));",
            "  col *= mix(1.0, 0.86, uTemper);",
            "  if (sp < 1.5) {",                        // 浅色肚皮
            "    float dBel = length((p + vec2(0.0, 0.14)) * vec2(1.0, 1.5)) - 0.30;",
            "    col = mix(col, mix(uTint, vec3(1.0), 0.62), m(dBel) * 0.8 * fill);",
            "  }",
            "  if (sp > 3.5 && sp < 4.5) {",            // 石头上的斑点
            "    float spk = m(length(p - vec2(-0.22, 0.16)) - 0.05)",
            "              + m(length(p - vec2( 0.26, -0.10)) - 0.04)",
            "              + m(length(p - vec2( 0.02, 0.26)) - 0.035);",
            "    col = mix(col, col * 0.70, clamp(spk, 0.0, 1.0) * 0.8 * fill);",
            "  }",
            "  if (sp > 5.5 && sp < 6.5) {",            // 星星仔的浅色脸蛋
            "    float dFace = length(p * vec2(1.0, 1.05)) - 0.26;",
            "    col = mix(col, mix(uTint, vec3(1.0), 0.55), m(dFace) * 0.85 * fill);",
            "  }",
            "  if (sp > 2.5 && sp < 3.5) {",            // 水母的透明亮带
            "    float band = smoothstep(0.22, 0.0, abs(p.y - 0.06));",
            "    col = mix(col, mix(uTint, vec3(1.0), 0.5), band * 0.45 * fill);",
            "  }",
            "  col = mix(col, uTint * 0.28, rim);",
            // 眼睛：随情绪放大/眯起/闭上
            "  float open = max(0.14, 1.0 - uBlink);",
            "  open *= mix(1.0, 0.58, angry);",
            "  open *= mix(1.0, 0.80, sleepy);",
            "  vec2 e0 = p - vec2(-eDX, eY) - look;",
            "  vec2 e1 = p - vec2( eDX, eY) - look;",
            "  e0.y /= open;",
            "  e1.y /= open;",
            "  float er = eR + startle * 0.020;",
            "  float eyes = max(m(length(e0 * vec2(1.0, 1.12)) - er),",
            "                   m(length(e1 * vec2(1.0, 1.12)) - er)) * fill;",
            "  float lineL = max(abs(p.y - eY) - 0.018, abs(p.x + eDX) - 0.075);",
            "  float lineR = max(abs(p.y - eY) - 0.018, abs(p.x - eDX) - 0.075);",
            "  float closed = max(m(lineL), m(lineR)) * fill;",
            "  float arcL = abs(length(p - vec2(-eDX, eY - 0.03)) - 0.075) - 0.020;",
            "  float arcR = abs(length(p - vec2( eDX, eY - 0.03)) - 0.075) - 0.020;",
            "  float arcs = max(m(arcL), m(arcR)) * step(eY - 0.03, p.y) * fill;",
            "  float wink = max(squish, smoothstep(0.45, 0.85, uBlink));",
            "  float eyeMask = mix(eyes, closed, wink);",
            "  eyeMask = mix(eyeMask, arcs, happy);",
            "  eyeMask = mix(eyeMask, closed, sleepy);",
            "  float hl = max(m(length(e0 - vec2(0.03, 0.03)) - 0.026),",
            "                 m(length(e1 - vec2(0.03, 0.03)) - 0.026)) * fill;",
            "  hl *= (1.0 - happy) * (1.0 - wink) * (1.0 - sleepy) * (1.0 - angry);",
            // 生气的眉毛
            "  float browOn = max(angry, step(0.68, uTemper) * (1.0 - happy) * (1.0 - sleepy));",
            "  float innerY = eY + mix(0.07, 0.02, angry);",
            "  float bl = sdSeg(p, vec2(-eDX - 0.10, eY + 0.16), vec2(-eDX + 0.08, innerY), 0.022);",
            "  float br = sdSeg(p, vec2( eDX + 0.10, eY + 0.16), vec2( eDX - 0.08, innerY), 0.022);",
            "  float brows = m(min(bl, br)) * fill * browOn;",
            // 嘴巴：好脾气笑，坏脾气皱眉
            "  float cx = clamp(p.x / mW, -1.0, 1.0);",
            "  float smile = mY - 0.09 * (1.0 - cx * cx);",
            "  float frown = mY + 0.07 * (1.0 - cx * cx);",
            "  float grumpy = max(step(0.65, uTemper) * (1.0 - happy), angry);",
            "  float curve = mix(smile, frown, grumpy);",
            "  float dSmile = max(abs(p.y - curve) - 0.016, abs(p.x) - mW);",
            "  float mouth = m(dSmile) * fill;",
            "  float dOpen = length((p - vec2(0.0, mY - 0.01)) * vec2(1.0, 1.1))",
            "             - (0.045 + happy * 0.02 + angry * 0.018);",
            "  mouth = mix(mouth, m(dOpen) * fill, max(max(startle, happy), angry * 0.85));",
            "  if (whisk > 0.5) {",                     // 猫的胡须
            "    float wl = min(sdSeg(p, vec2(-0.44, -0.18), vec2(-0.70, -0.12), 0.013),",
            "                     sdSeg(p, vec2(-0.44, -0.26), vec2(-0.70, -0.30), 0.013));",
            "    float wr = min(sdSeg(p, vec2( 0.44, -0.18), vec2( 0.70, -0.12), 0.013),",
            "                     sdSeg(p, vec2( 0.44, -0.26), vec2( 0.70, -0.30), 0.013));",
            "    whisk = m(min(wl, wr)) * fill;",
            "  } else {",
            "    whisk = 0.0;",
            "  }",
            "  float blush = m(length((p - vec2(-eDX - 0.13, mY + 0.03)) * vec2(1.0, 1.3)) - 0.08)",
            "              + m(length((p - vec2( eDX + 0.13, mY + 0.03)) * vec2(1.0, 1.3)) - 0.08);",
            "  col = mix(col, vec3(1.0, 0.42, 0.52),",
            "            clamp(blush, 0.0, 1.0) * (0.20 + 0.40 * happy) * fill",
            "            * (1.0 - uTemper) * (1.0 - angry));",
            "  vec3 ink = vec3(0.10, 0.08, 0.13);",
            "  col = mix(col, ink, max(max(eyeMask, mouth), max(brows, whisk)));",
            "  col = mix(col, vec3(1.0), hl);",
            "  col = mix(col, vec3(1.0, 0.93, 0.55), m(dTip) * startle);",
            "  vec3 outc = mix(vec3(0.02, 0.02, 0.05), col, fill);",
            "  float alpha = max(fill, shadow * 0.22);",
            "  gl_FragColor = vec4(outc, alpha * uAlpha);",
            "}",
            "void heart() {",
            "  vec2 p = vP;",
            "  float dc = min(length(p - vec2(-0.30, 0.24)) - 0.38,",
            "                 length(p - vec2(0.30, 0.24)) - 0.38);",
            "  float dd = max(max(abs(p.x - p.y), abs(p.x + p.y)) - 0.78, p.y - 0.24);",
            "  gl_FragColor = vec4(uTint, m(min(dc, dd)) * uAlpha);",
            "}",
            "void star() {",
            "  vec2 p = vP;",
            "  float ang = atan(p.y, p.x);",
            "  float rad = 0.30 + 0.26 * cos(5.0 * ang + 1.5708);",
            "  gl_FragColor = vec4(uTint, m(length(p) - rad) * uAlpha);",
            "}",
            "void ripple() {",
            "  float a = m(abs(length(vP) - 0.70) - 0.09);",
            "  gl_FragColor = vec4(uTint, a * uAlpha);",
            "}",
            "void puff() {",
            "  float a = smoothstep(0.95, 0.15, length(vP));",
            "  gl_FragColor = vec4(uTint, a * a * uAlpha);",
            "}",
            "void main() {",
            "  if (uShape < 0.5) { creature(); }",
            "  else if (uShape < 1.5) { heart(); }",
            "  else if (uShape < 2.5) { star(); }",
            "  else if (uShape < 3.5) { ripple(); }",
            "  else { puff(); }",
            "}"
    );

    /** 用于把模糊结果缩到 16x16 内容图，供小精灵选址。 */
    static final String FS_COPY = glsl(
            "precision mediump float;",
            "varying vec2 vUv;",
            "uniform sampler2D uTex;",
            "void main() { gl_FragColor = texture2D(uTex, vUv); }"
    );
}
